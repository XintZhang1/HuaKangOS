import html
import json
import re
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/trial-source'
CATALOGUE = ROOT / 'docs/workflow-source'
OUT = ROOT / 'docs/试用脚本'
PORTABLE = ROOT / 'docs/试用操作手册-XC.html'
INDEX_NAME = '总表.md'
# Must stay identical to app/security.py ROLES keys; tests/test_trial_scripts.py compares them.
ROLES = {'admin', 'manager', 'sales', 'inventory', 'service', 'finance', 'auditor',
         'reception', 'technician', 'customer_service'}
# Same labels as web/workflowcontent.js so the scripts read like the pages do.
ROLE_LABELS = {'admin': '管理员', 'manager': '店长', 'sales': '销售', 'service': '服务顾问',
               'customer_service': '客服', 'reception': '接待', 'inventory': '库管',
               'technician': '技师', 'finance': '财务', 'auditor': '复核人员'}
CHANNELS = ('manual', 'search', 'assistant')
BRANCH_KINDS = ('refusal', 'duplicate', 'stale', 'cross-store', 'edge')
STEP_KEYS = ('no', 'actor', 'account', 'workflow', 'route', 'channel', 'entry', 'search', 'assistant', 'action', 'expect')
ROUND_COUNT = 41


def read(path):
    return json.loads(Path(path).read_text('utf-8-sig'))


def text(value, label):
    assert isinstance(value, str) and value.strip(), label
    return value.strip()


def requirement_workflow_maps():
    """Published authority: requirement register, group mapping and workflow sources."""
    register = read(ROOT / 'docs/requirements.json')
    requirements = {row['id']: row for row in register['requirements']}
    assert len(requirements) == 193, 'requirement register changed'
    coverage = read(CATALOGUE / 'coverage.json')
    groups = {}
    for row in coverage['mapping']:
        entry = groups.setdefault((row['module'], row['group']), {'requirements': [], 'workflows': []})
        entry['requirements'].append({'id': row['id'], 'title': row['title']})
        for workflow_id in row['workflow_ids']:
            if workflow_id not in entry['workflows']:
                entry['workflows'].append(workflow_id)
    workflows = {}
    for name in ('business.json', 'services.json'):
        for item in read(CATALOGUE / name):
            assert item['id'] not in workflows, 'duplicate workflow ' + item['id']
            workflows[item['id']] = item
    assert all(workflow_id in workflows for entry in groups.values() for workflow_id in entry['workflows'])
    return requirements, groups, workflows


def normalise(value):
    """Same normalisation as web/workflowcontent.js so a search term means the same thing."""
    value = unicodedata.normalize('NFKC', str(value or '')).lower().replace('预定', '预订')
    return ''.join(ch for ch in value if not ch.isspace() and unicodedata.category(ch)[0] not in ('P', 'S'))


def search_haystack(workflow, requirements):
    parts = [workflow['title'], workflow['category'], workflow['summary'], workflow['entry']['label']]
    parts += list(workflow.get('keywords') or [])
    parts += [step['where'] for step in workflow.get('manual') or []]
    parts += [issue['when'] for issue in workflow.get('exceptions') or []]
    for requirement_id in workflow['requirement_ids']:
        row = requirements[requirement_id]
        parts += [requirement_id, row['title'], row['group']]
    return normalise(' '.join(parts))


def search_hits(term, workflow, requirements):
    hay = search_haystack(workflow, requirements)
    words = [normalise(word) for word in str(term or '').split()]
    return all(word and word in hay for word in words)


def search_rank(term, workflows, requirements):
    """Order the catalogue the way the in-page search box does, ignoring the per-role bonus."""
    query = normalise(term)
    hits = [workflow for workflow in workflows if search_hits(term, workflow, requirements)]

    def score(workflow):
        title = normalise(workflow['title'])
        keys = [normalise(key) for key in workflow['keywords']]
        entry = normalise(workflow['entry']['label']).removeprefix(normalise('打开'))
        requirements_text = [normalise(rid + ' ' + requirements[rid]['title'])
                             for rid in workflow['requirement_ids']]
        return ((100 if title == query else 0) + (60 if entry == query else 0)
                + (40 if title.startswith(query) else 0) + (25 if query in title else 0)
                + (20 if query in keys else 0)
                + (12 if any(query in text for text in requirements_text) else 0))

    return sorted(hits, key=lambda workflow: (-score(workflow), workflow['title']))


def app_routes():
    """Route tokens actually dispatched by the front end; scripts must not invent pages."""
    source = (ROOT / 'web/app.js').read_text('utf-8')
    found = set(re.findall(r"type==='([a-z][a-z0-9/-]*)'", source))
    found |= set(re.findall(r"nav\('([a-z][a-z0-9/-]*)'", source))
    return {route for route in found if route}


def make_data():
    world = read(SOURCE / 'world.json')
    rounds_source = read(SOURCE / 'rounds.json')
    requirements, groups, workflows = requirement_workflow_maps()
    routes = app_routes()

    assert world['schema_version'] == 1 and rounds_source['schema_version'] == 1, 'unsupported source schema'
    assert world['code'] == rounds_source['code'], 'world and rounds must share one code'
    text(world['title'], 'world title')
    text(rounds_source['title'], 'rounds title')
    accounts = world['accounts']
    assert accounts, 'world needs at least one account'
    usernames = set()
    for account in accounts:
        text(account['username'], 'account username')
        assert account['username'] not in usernames, 'duplicate account ' + account['username']
        usernames.add(account['username'])
        assert account['role'] in ROLES, account['username'] + ' has an unknown role'
        text(account['display_name'], 'account display name')
    for convention in world['conventions']:
        for key in ('label', 'value', 'note'):
            text(convention[key], 'convention ' + key)
    for section in world['sections']:
        text(section['title'], 'section title')
        assert section['kind'] in ('table', 'list', 'text'), section['title']
        if section['kind'] == 'table':
            assert section['columns'] and section['rows'], 'empty table in ' + section['title']
            assert all(len(row) == len(section['columns']) for row in section['rows']), 'column mismatch in ' + section['title']
        elif section['kind'] == 'list':
            assert section['items'], 'empty list in ' + section['title']
        else:
            text(section['text'], 'section text')

    rounds = rounds_source['rounds']
    assert len(rounds) == ROUND_COUNT, 'expected %d rounds' % ROUND_COUNT
    seen_groups, seen_slugs = set(), set()
    for index, item in enumerate(rounds, start=1):
        assert item['id'] == 'R%02d' % index, 'rounds must be listed in order: ' + item['id']
        assert item['status'] in ('outline', 'detailed'), item['id']
        key = (item['module'], item['group'])
        assert key in groups, 'unknown module/group: %s / %s' % key
        assert key not in seen_groups, 'group appears twice: %s' % (key,)
        seen_groups.add(key)
        text(item['title'], item['id'] + ' title')
        text(item['slug'], item['id'] + ' slug')
        assert item['slug'] not in seen_slugs, 'duplicate slug ' + item['slug']
        seen_slugs.add(item['slug'])
        text(item['scenario'], item['id'] + ' scenario')
        assert item['prerequisites'], item['id'] + ' prerequisites'
        for note in item['prerequisites']:
            text(note, item['id'] + ' prerequisite')
        mapping = groups[key]
        item['requirements'] = list(mapping['requirements'])
        item['workflows'] = [workflows[workflow_id] for workflow_id in mapping['workflows']]
        if item['status'] == 'outline':
            continue
        assert item.get('data'), item['id'] + ' data'
        for row in item['data']:
            for field in ('label', 'value', 'note'):
                text(row[field], item['id'] + ' data field')
        assert item.get('steps'), item['id'] + ' steps'
        numbers = set()
        for step in item['steps']:
            for field in STEP_KEYS:
                assert field in step, '%s step misses %s' % (item['id'], field)
            text(step['no'], item['id'] + ' step number')
            assert step['no'] not in numbers, 'duplicate step ' + step['no']
            numbers.add(step['no'])
            assert step['channel'] in CHANNELS, step['no']
            text(step['actor'], step['no'] + ' actor')
            text(step['action'], step['no'] + ' action')
            text(step['expect'], step['no'] + ' expect')
            assert step['workflow'] in workflows, step['no'] + ' unknown workflow'
            workflow = workflows[step['workflow']]
            assert step['workflow'] in mapping['workflows'], step['no'] + ' workflow outside this group'
            assert isinstance(step.get('optional', False), bool), step['no'] + ' optional'
            if step['account']:
                assert step['account'] in usernames, step['no'] + ' unknown account'
            route = step['route']
            if route:
                known = routes | {item['entry']['route'] for item in workflows.values()}
                assert route in known, step['no'] + ' unknown route ' + route
            if step['search']:
                assert search_hits(step['search'], workflow, requirements), \
                    '%s search %r does not reach %s' % (step['no'], step['search'], step['workflow'])
                ranked = [flow['id'] for flow in search_rank(step['search'], list(workflows.values()), requirements)][:3]
                assert step['workflow'] in ranked, \
                    '%s search %r leads to %s, not %s' % (step['no'], step['search'], ranked, step['workflow'])
            if step['assistant']:
                text(workflow['assistant']['prompt'], step['no'] + ' assistant prompt')
        for branch in item.get('branches') or []:
            assert branch['kind'] in BRANCH_KINDS, item['id'] + ' branch kind'
            text(branch['action'], item['id'] + ' branch action')
            text(branch['expect'], item['id'] + ' branch expectation')
        for note in item.get('observations') or []:
            text(note, item['id'] + ' observation')
        assert item.get('observations'), item['id'] + ' observations'
        assert item.get('checks'), item['id'] + ' checks'
        for note in item['checks']:
            text(note, item['id'] + ' check')
        text(item['report_check'], item['id'] + ' report check')
    return {'world': world, 'rounds': rounds, 'requirements': requirements,
            'groups': groups, 'workflows': workflows,
            'detailed': [item for item in rounds if item['status'] == 'detailed']}


def table(columns, rows):
    lines = ['| ' + ' | '.join(columns) + ' |', '|' + '---|' * len(columns)]
    for row in rows:
        lines.append('| ' + ' | '.join(str(cell) for cell in row) + ' |')
    return '\n'.join(lines)


def world_markdown(world, level=2):
    out = ['%s 虚拟世界设定 · %s' % ('#' * level, world['title']), '',
           '%s 账号' % ('#' * (level + 1)), '',
           table(['登录账号', '员工姓名', '岗位代码', '门店', '用途'],
                 [[a['username'], a['display_name'], a['role'], a['store'], a['purpose']] for a in world['accounts']]),
           '', '%s 约定' % ('#' * (level + 1)), '',
           table(['项目', '取值', '说明'],
                 [[c['label'], c['value'], c['note']] for c in world['conventions']])]
    for section in world['sections']:
        out += ['', '%s %s' % ('#' * (level + 1), section['title']), '']
        if section['kind'] == 'table':
            out.append(table(section['columns'], section['rows']))
        elif section['kind'] == 'list':
            out += ['- ' + item for item in section['items']]
        else:
            out.append(section['text'])
    return '\n'.join(out) + '\n'


def requirement_rows(item):
    return [[row['id'], row['title']] for row in item['requirements']]


def workflow_rows(item):
    return [[workflow['title'], workflow['entry']['label'], workflow['entry']['route'],
             '、'.join(ROLE_LABELS[role] for role in workflow['entry']['roles'])]
            for workflow in item['workflows']]


def requirement_range(item):
    first, last = item['requirements'][0]['id'], item['requirements'][-1]['id']
    return first if first == last else '%s–%s' % (first, last)


