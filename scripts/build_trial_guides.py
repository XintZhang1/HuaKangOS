def build(check=False):
    data = make_data()
    outputs = {OUT / INDEX_NAME: index_markdown(data), PORTABLE: page(data)}
    for item in data['detailed']:
        outputs[OUT / ('%s-%s.md' % (item['id'], item['slug']))] = round_markdown(item, data['world'])
    for path, content in outputs.items():
        if check:
            assert path.is_file() and path.read_text('utf-8') == content, 'Generated file differs: ' + str(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    summary = {'rounds': len(data['rounds']), 'detailed': len(data['detailed']),
               'outline': len(data['rounds']) - len(data['detailed']),
               'requirements': len(data['requirements']), 'workflows': len(data['workflows']),
               'outputs': sorted(str(path.relative_to(ROOT)) for path in outputs)}
    print(json.dumps(summary, ensure_ascii=False))
    return summary


